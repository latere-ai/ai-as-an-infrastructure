// A reference architecture for the stack a model builder runs, by layer: the
// data plane (sources and rights, extraction and filtering, tokenization and
// mixture, the shard store, and post-training data), the training runtime with
// its checkpoint store and experiment tracker, the RL post-training loop
// (rollout engines, the environment fleet, rewards and verifiers), the
// evaluation gate and release, and compute. Arrows are hand-offs; each arrow's
// color is what the hand-off carries: data, weights, trajectories and rewards,
// or evidence (metrics and evaluation results). The figure answers where each
// kind of artifact travels: data moves one way into the trainer, weights leave
// the trainer for three destinations (the checkpoint store, the rollout
// engines, and, through the gate, release), and trajectories return to the
// trainer only through the rewards and verifiers.
//
// Selecting a component shows what it does, example projects, the section of
// the chapter that covers it, and each hand-off in and out. With nothing
// selected, the readout groups every hand-off by what it carries.
//
// The components and hand-offs restate the chapter's prose. The example
// projects are illustrative, not recommendations, and were checked on 25
// September 2026 against each project's own repository or documentation; the
// chapter's dated blocks cite them:
// - data: github.com/huggingface/datatrove, github.com/NVIDIA-NeMo/Curator,
//   github.com/mosaicml/streaming, Megatron-LM's weighted --data-path
// - runtime and checkpoints: github.com/NVIDIA/Megatron-LM (CheckpointConfig),
//   github.com/pytorch/torchtitan, github.com/deepspeedai/DeepSpeed,
//   github.com/AI-Hypercomputer/maxtext, PyTorch Distributed Checkpoint,
//   github.com/google/orbax
// - RL: github.com/verl-project/verl, github.com/OpenRLHF/OpenRLHF,
//   github.com/NVIDIA-NeMo/RL, github.com/NovaSky-AI/SkyRL,
//   github.com/PrimeIntellect-ai/prime-rl, github.com/THUDM/slime,
//   github.com/areal-project/AReaL; the vLLM weight-transfer API
//   (vllm.ai/blog/2026-05-28-native-rl-apis) and SGLang's RL endpoints
// - environments: github.com/huggingface/OpenEnv,
//   github.com/PrimeIntellect-ai/verifiers, SkyRL-Gym, github.com/huggingface/Math-Verify
// - gate and release: github.com/EleutherAI/lm-evaluation-harness, Inspect,
//   safetensors, the OpenSSF model signing specification
// - compute: Slurm 26.05, Kueue (Topology Aware Scheduling), JobSet

