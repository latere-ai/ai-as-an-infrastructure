interface Box { x0: number; x1: number; y0: number; y1: number; cx: number; cy: number }
type Pt = [number, number];

const PAD = 8;
const NAME = TYPE.label, EX = TYPE.small;
const NAME_LH = NAME + 4, EX_LH = EX + 4;

function boxLines(c: Comp, width: number, lang: Lang) {
  const inner = width - 2 * PAD;
  return { name: wrapLines(c.name[lang], NAME, inner), ex: wrapLines(c.examples[lang], EX, inner) };
}
const boxHeight = (ls: { name: string[]; ex: string[] }) =>
  PAD + ls.name.length * NAME_LH + 2 + ls.ex.length * EX_LH + PAD - 4;

function drawBox(c: Comp, b: Box, lang: Lang, st: { sel: Sel; dim: boolean }, extraLines: string[] = []): string {
  const ls = boxLines(c, b.x1 - b.x0, lang);
  const isSel = st.sel === c.id;
  const parts: string[] = [];
  parts.push(el("rect", { x: b.x0, y: b.y0, width: b.x1 - b.x0, height: b.y1 - b.y0, rx: 6, fill: C.paper, stroke: isSel ? C.ink : C.rule, "stroke-width": isSel ? 2 : 1 }));
  let y = b.y0 + PAD + NAME - 1;
  for (const ln of ls.name) { parts.push(text(b.x0 + PAD, y, ln, { "font-size": NAME, class: "fig-t-strong" })); y += NAME_LH; }
  y += 2 - (NAME_LH - EX_LH) - 1;
  for (const ln of ls.ex) { parts.push(text(b.x0 + PAD, y, ln, { "font-size": EX, class: "fig-t-muted" })); y += EX_LH; }
  if (extraLines.length) parts.push(...extraLines);
  return g({ opacity: st.dim ? 0.5 : undefined, "data-fig-set": `component=${c.id}`, class: "fig-hit" }, ...parts);
}

function arrowHead(pts: Pt[], color: string): string {
  const [x1, y1] = pts[pts.length - 1];
  const [x0, y0] = pts[pts.length - 2];
  const len = Math.hypot(x1 - x0, y1 - y0) || 1;
  const ux = (x1 - x0) / len, uy = (y1 - y0) / len;
  const s = 7, hw = 4;
  const bx = x1 - ux * s, by = y1 - uy * s;
  return el("path", { d: `M${x1},${y1}L${bx - uy * hw},${by + ux * hw}L${bx + uy * hw},${by - ux * hw}Z`, fill: color });
}

function trimmed(pts: Pt[], by = 6): Pt[] {
  const out = pts.map((p) => [...p] as Pt);
  const n = out.length;
  const [x1, y1] = out[n - 1], [x0, y0] = out[n - 2];
  const len = Math.hypot(x1 - x0, y1 - y0) || 1;
  out[n - 1] = [x1 - ((x1 - x0) / len) * by, y1 - ((y1 - y0) / len) * by];
  return out;
}

const pathOf = (pts: Pt[]) => pts.map(([x, y], i) => `${i ? "L" : "M"}${Math.round(x * 10) / 10},${Math.round(y * 10) / 10}`).join("");

function edge(pts: Pt[], color: string, on: boolean, dim: boolean): string {
  return g({ opacity: dim ? 0.22 : undefined },
    el("path", { d: pathOf(trimmed(pts)), fill: "none", stroke: color, "stroke-width": on ? 2.8 : 1.8, "stroke-linejoin": "round" }),
    arrowHead(pts, color));
}

// ---------------------------------------------------------------- desktop layout

// Four columns inside groups that span the width between margins. Rows from the
// top: the data plane (the four pipeline stages, then post-training data under
// the first two); the training runtime (checkpoint store over experiment
// tracking in the first column, the trainer across the other three); the RL
// group across the last three columns (rollout engines beside the rewards and
// verifiers, the environment fleet under both); the evaluation gate and
// release; compute. The left margin carries candidate checkpoints down to the
// gate, and the gate's scores rise through the empty first column of the RL
// row into the tracker. Group captions sit on the side no arrow enters from.
const M = 20, GUT = 18, GAP = 28, CAP = 20, INSET = 8, INNER = 20, STACK = 12;

interface Group { layer: Layer; x0: number; x1: number; y0: number; y1: number; right: boolean }

function desktop(w: number, lang: Lang) {
  const X0 = M + INSET, X1 = w - M - INSET;
  const colW = (X1 - X0 - 3 * GUT) / 4;
  const col = (i: number): [number, number] => [X0 + i * (colW + GUT), X0 + i * (colW + GUT) + colW];
  const span = (a: number, b: number): [number, number] => [col(a)[0], col(b)[1]];
  const B = new Map<Id, Box>();
  const groups: Group[] = [];
  const put = (id: Id, x0: number, x1: number, y0: number, h: number) =>
    B.set(id, { x0, x1, y0, y1: y0 + h, cx: (x0 + x1) / 2, cy: y0 + h / 2 });
  const hOf = (id: Id, width: number) => boxHeight(boxLines(byId.get(id)!, width, lang));
  const row = (ids: Array<[Id, [number, number]]>, y: number) => {
    const h = Math.max(...ids.map(([id, [x0, x1]]) => hOf(id, x1 - x0)));
    for (const [id, [x0, x1]] of ids) put(id, x0, x1, y, h);
    return h;
  };
  let y = 0;
  // Data plane.
  const dTop = y;
  const hA = row([["sources", col(0)], ["process", col(1)], ["tokenize", col(2)], ["shards", col(3)]], dTop + CAP);
  const yA2 = dTop + CAP + hA + INNER;
  const hA2 = row([["ptdata", span(0, 1)]], yA2);
  const dBot = yA2 + hA2 + INSET;
  groups.push({ layer: "data", x0: M, x1: w - M, y0: dTop, y1: dBot, right: false });
  // Training runtime: the checkpoint store over the tracker, the trainer beside both.
  const rTop = dBot + GAP;
  const yB = rTop + CAP;
  const hCk = hOf("ckpt", colW), hTr = hOf("tracking", colW);
  const leftH = hCk + STACK + hTr;
  const hT = Math.max(leftH, hOf("trainer", span(1, 3)[1] - span(1, 3)[0]));
  put("ckpt", col(0)[0], col(0)[1], yB, hCk + (hT - leftH) / 2);
  put("tracking", col(0)[0], col(0)[1], B.get("ckpt")!.y1 + STACK, hTr + (hT - leftH) / 2);
  put("trainer", span(1, 3)[0], span(1, 3)[1], yB, hT);
  const rBot = yB + hT + INSET;
  groups.push({ layer: "runtime", x0: M, x1: w - M, y0: rTop, y1: rBot, right: false });
  // RL post-training, over the last three columns.
  const lTop = rBot + GAP;
  const hC1 = row([["rollout", col(1)], ["reward", span(2, 3)]], lTop + CAP);
  const yC2 = lTop + CAP + hC1 + INNER;
  const hC2 = row([["envs", span(1, 3)]], yC2);
  const lBot = yC2 + hC2 + INSET;
  groups.push({ layer: "rl", x0: col(1)[0] - INSET, x1: w - M, y0: lTop, y1: lBot, right: true });
  // Evaluation and release.
  const eTop = lBot + GAP;
  row([["gate", col(0)], ["release", span(1, 2)]], eTop + CAP);
  const eBot = B.get("gate")!.y1 + INSET;
  groups.push({ layer: "gates", x0: M, x1: w - M, y0: eTop, y1: eBot, right: true });
  // Compute.
  const cTop = eBot + GAP;
  row([["scheduler", span(0, 1)], ["accel", span(2, 3)]], cTop + CAP);
  const cBot = B.get("scheduler")!.y1 + INSET;
  groups.push({ layer: "compute", x0: M, x1: w - M, y0: cTop, y1: cBot, right: false });
  return { B, groups, height: cBot, col };
}

function desktopRoute(h: Hop, lay: ReturnType<typeof desktop>, w: number): Pt[] {
  const { B, col } = lay;
  const a = B.get(h.from)!;
  if (h.to === "out") return [[a.x1, a.cy], [w - 2, a.cy]];
  const b = B.get(h.to)!;
  switch (`${h.from}>${h.to}`) {
    case "sources>process": case "process>tokenize": case "tokenize>shards": case "rollout>reward": case "gate>release":
      return [[a.x1, a.cy], [b.x0, a.cy]];
    case "shards>trainer": return [[a.cx, a.y1], [a.cx, b.y0]];
    case "ptdata>trainer": { const x = col(1)[0] + (col(1)[1] - col(1)[0]) / 2; return [[x, a.y1], [x, b.y0]]; }
    case "trainer>ckpt": return [[a.x0, b.cy - 5], [b.x1, b.cy - 5]];
    case "ckpt>trainer": return [[a.x1, a.cy + 5], [b.x0, a.cy + 5]];
    case "trainer>tracking": return [[a.x0, b.cy], [b.x1, b.cy]];
    case "trainer>rollout": return [[b.cx, a.y1], [b.cx, b.y0]];
    case "rollout>envs": return [[a.cx - 6, a.y1], [a.cx - 6, b.y0]];
    case "envs>rollout": return [[b.cx + 6, a.y0], [b.cx + 6, b.y1]];
    case "envs>reward": return [[b.cx, a.y0], [b.cx, b.y1]];
    case "reward>trainer": return [[a.cx, a.y0], [a.cx, b.y1]];
    case "ckpt>gate": return [[a.x0, a.cy], [M / 2, a.cy], [M / 2, b.cy], [b.x0, b.cy]];
    case "gate>tracking": return [[a.cx, a.y0], [a.cx, b.y1]];
  }
  return [[b.cx, a.y1], [b.cx, b.y0]];
}

// ---------------------------------------------------------------- phone layout

// One column, top to bottom in layer order. Each box lists its outgoing
// hand-offs under its examples, with the swatch of what each one carries.
const LAYER_ORDER: readonly Layer[] = ["data", "runtime", "rl", "gates", "compute"];
const HOP_SIZE = TYPE.small, HOP_LH = HOP_SIZE + 5, SW = 16;

function phoneHops(c: Comp, x0: number, width: number, lang: Lang) {
  const L = labels[lang];
  const rows: Array<{ lines: string[]; color: string }> = [];
  for (const h of HOPS.filter((h) => h.from === c.id)) {
    rows.push({ lines: wrapLines(tpl(L.phoneOut, { to: lead(nameOf(h.to, lang), lang), kind: KINDS[h.kind][lang] }), HOP_SIZE, width - 2 * PAD - SW - 6), color: KIND_COLOR[h.kind] });
  }
  const n = rows.reduce((s, r) => s + r.lines.length, 0);
  const draw = (yStart: number): string[] => {
    const out: string[] = [];
    let yy = yStart;
    for (const r of rows) {
      out.push(el("line", { x1: x0 + PAD, x2: x0 + PAD + SW, y1: yy - 4, y2: yy - 4, stroke: r.color, "stroke-width": 2.4 }));
      for (const ln of r.lines) { out.push(text(x0 + PAD + SW + 6, yy, ln, { "font-size": HOP_SIZE })); yy += HOP_LH; }
    }
    return out;
  };
  return { height: n ? n * HOP_LH + 4 : 0, draw };
}

function phone(w: number, lang: Lang, sel: Sel, dimBox: (id: Id) => boolean): { svg: string; h: number } {
  const parts: string[] = [];
  let y = 0;
  for (const layer of LAYER_ORDER) {
    const comps = COMPS.filter((c) => c.layer === layer);
    const x0 = INSET, x1 = w - INSET;
    const top = y;
    let yy = y + CAP;
    const inner: string[] = [];
    comps.forEach((c, i) => {
      const ls = boxLines(c, x1 - x0, lang);
      const hops = phoneHops(c, x0, x1 - x0, lang);
      const base = boxHeight(ls);
      const h = base + hops.height;
      const b: Box = { x0, x1, y0: yy, y1: yy + h, cx: (x0 + x1) / 2, cy: yy + h / 2 };
      inner.push(drawBox(c, b, lang, { sel, dim: dimBox(c.id) }, hops.draw(yy + base + HOP_SIZE - 2)));
      yy += h + (i < comps.length - 1 ? 8 : 0);
    });
    yy += INSET;
    parts.push(el("rect", { x: 0, y: top, width: w, height: yy - top, rx: 8, fill: C.panel }));
    parts.push(text(INSET, top + 14, LAYERS[layer][lang], { "font-size": TYPE.small, class: "fig-t-muted" }));
    parts.push(...inner);
    y = yy + 10;
  }
  return { svg: g({ class: "fig-stack" }, ...parts), h: y - 10 };
}

