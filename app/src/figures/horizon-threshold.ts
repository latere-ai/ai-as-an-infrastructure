// A capability horizon read off a fitted success curve, and the published
// horizons it produces across models.
//
// Top panel: the chapter's model Pr(Y = 1 | d) = σ(α − β ln d) with d in
// minutes of human task time, parametrized by the 50 percent horizon h50 and
// the slope β, so α = β ln h50 and the horizon at threshold q is
// h_q = exp((α − logit q) / β) = h50 · exp(−logit q / β). Dragging β pivots
// the curve about (h50, 0.5), which is why the ratio
// h50 / h80 = exp(logit 0.8 / β) depends on the slope alone. h50 and the
// starting β come from a model's published METR fit: the file gives h50 and
// h80 from one logistic fit per model, so β = logit 0.8 / ln(h50 / h80)
// recovers that fit's slope exactly. The dots are illustrative: 48 tasks,
// log-uniform from 1 second to 1 day, eight attempts each, drawn from the
// curve with a seeded generator. They show what a fit sees; the curve is
// the model, not a refit to the dots.
//
// Bottom panel: METR-Horizon-v1.1 per-model 50 and 80 percent horizons by
// release date (data/metr-horizon.ts, generated by
// tools/figure-data/metr-horizon.py). Trend lines are least-squares fits of
// log2 horizon on release date over the models METR flags as the frontier at
// release, inside the chosen window, excluding central 50 percent estimates
// above 16 hours. For the 50 percent series this rule reproduces METR's
// published doubling times (187.8 days for all history, 128.7 from 2023); the
// 80 percent line applies the same rule and is not a METR figure. METR
// publishes only the two thresholds, so this panel does not move with q.

