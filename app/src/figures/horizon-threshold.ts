// Seeded task times and attempt draws; outcomes are u < p(d), so they move
// monotonically as the curve moves.
const drawMemo = new Map<number, { d: number[]; u: number[][] }>();
function draws(seed: number) {
  const hit = drawMemo.get(seed);
  if (hit) return hit;
  const r = rng(seed);
  const l0 = Math.log(TASK_MIN), l1 = Math.log(TASK_MAX);
  const d: number[] = [], u: number[][] = [];
  for (let i = 0; i < TASKS; i++) {
    d.push(Math.exp(l0 + ((i + r()) / TASKS) * (l1 - l0)));
    u.push(Array.from({ length: ATTEMPTS }, () => r()));
  }
  const out = { d, u };
  drawMemo.set(seed, out);
  return out;
}

const success = (d: number, h50: number, beta: number) => sigmoid(beta * (Math.log(h50) - Math.log(d)));
const horizon = (q: number, h50: number, beta: number) => h50 * Math.exp(-logit(q) / beta);

const dayNum = (iso: string) => {
  const [y, m, d] = iso.split("-").map(Number);
  return Date.UTC(y, m - 1, d) / 86400000;
};

// Which models enter the trend fit: METR's rule inside the chosen window.
function status(m: HorizonModel, win: Win): "fit" | "notFrontier" | "ceiling" | "window" {
  if (!m.frontier) return "notFrontier";
  if (m.p50[0] > CEILING_MIN) return "ceiling";
  if (win === "2023" && m.released < "2023-01-01") return "window";
  return "fit";
}

interface Trend { slope: number; mx: number; my: number; x0: number; x1: number; n: number; days: number }
function trend(win: Win, k: 0 | 1): Trend {
  const pts = MODELS.filter((m) => status(m, win) === "fit").map((m) => [dayNum(m.released), Math.log2((k ? m.p80 : m.p50)[0])] as const);
  const n = pts.length;
  const mx = pts.reduce((s, p) => s + p[0], 0) / n, my = pts.reduce((s, p) => s + p[1], 0) / n;
  const slope = pts.reduce((s, p) => s + (p[0] - mx) * (p[1] - my), 0) / pts.reduce((s, p) => s + (p[0] - mx) ** 2, 0);
  return { slope, mx, my, x0: Math.min(...pts.map((p) => p[0])), x1: Math.max(...pts.map((p) => p[0])), n, days: 1 / slope };
}

