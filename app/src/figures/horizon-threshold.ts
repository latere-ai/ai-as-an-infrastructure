function lines(s: string, lang: Lang, fs: number, w: number) {
  return lang === "zh" ? wrapCjk(s, fs, w) : wrap(s, fs, w);
}

function render(st: State<P>, lang: Lang): string {
  const L = labels[lang];
  const p = st.p;
  const w = st.w;
  const narrow = w < 480;
  const fs = TYPE.body;
  const m = BY_ID.get(p.model) ?? DEFAULT_MODEL;
  const bPub = betaOf(m);
  const onPub = Math.abs(p.beta - bPub) < 1e-6 && Math.abs(p.h50 - m.p50[0]) < 1e-9;
  const parts: string[] = [];
  const left = narrow ? 40 : 46, right = narrow ? 6 : 12;

  // ================= panel A: the success curve
  let y = 0;
  for (const ln of lines(L.headA, lang, TYPE.label, w)) { y += 18; parts.push(text(0, y - 2, ln, { "font-size": TYPE.label, class: "fig-t-strong" })); }
  y += 10;
  // Legend: curve, published curve (when the slope differs), dots.
  {
    const items: Array<{ label: string; draw: (x: number, yy: number) => string }> = [
      { label: L.legCurve, draw: (x, yy) => el("line", { x1: x, x2: x + 18, y1: yy - 4, y2: yy - 4, stroke: C.c1, "stroke-width": 2.5 }) },
    ];
    if (!onPub) items.push({ label: tpl(L.legPub, { name: nameOf(m, lang) }), draw: (x, yy) => el("line", { x1: x, x2: x + 18, y1: yy - 4, y2: yy - 4, stroke: C.ink2, "stroke-width": 1.5, "stroke-dasharray": "4 3" }) });
    items.push({ label: L.legDots, draw: (x, yy) => el("circle", { cx: x + 9, cy: yy - 4, r: 3.5, fill: C.ink2, "fill-opacity": 0.55 }) });
    let cx = 0, row = 0;
    for (const it of items) {
      const iw = 24 + textWidth(it.label, fs);
      if (cx > 0 && cx + iw > w) { cx = 0; row++; }
      const yy = y + 14 + row * 20;
      parts.push(it.draw(cx, yy), text(cx + 24, yy, it.label, { "font-size": fs, class: "fig-t-muted" }));
      cx += iw + 16;
    }
    y += 14 + row * 20 + 16;
  }
  const topA = y + 14;
  const hA = narrow ? 190 : 220;
  // Keep the last time label ("1 wk") inside the figure.
  const rightA = Math.max(right, Math.ceil(textWidth(tickDur(lang)(XA[1]), fs) / 2) + 2);
  const xa = log(XA, [left, w - rightA]);
  const ya = linear([0, 1], [topA + hA, topA]);
  parts.push(axis({ scale: xa, orient: "bottom", at: topA + hA, grid: [topA, topA + hA], ticks: [1 / 60, 1, 60, 1440, 10080], format: tickDur(lang), title: L.xA, size: fs }));
  parts.push(axis({ scale: ya, orient: "left", at: left, grid: [left, w - rightA], ticks: [0, 0.2, 0.5, 0.8, 1], format: (v) => `${Math.round(v * 100)}%`, title: L.yA, size: fs }));

  // Simulated outcomes.
  // Label obstacles are the curve and the guide lines; labels carry a halo,
  // so they may sit over a dot.
  const dr = draws(p.seed);
  const obstacles: Box[] = [];
  for (let i = 0; i < TASKS; i++) {
    const pr = success(dr.d[i], p.h50, p.beta);
    const k = dr.u[i].filter((u) => u < pr).length;
    parts.push(el("circle", { cx: xa(dr.d[i]), cy: ya(k / ATTEMPTS), r: narrow ? 2.6 : 3.2, fill: C.ink2, "fill-opacity": 0.5 }));
  }
  // Curves: the published fit (dashed, when the slope has moved) and the chosen one.
  const curvePts = (beta: number) => {
    const n = 160, l0 = Math.log(XA[0]), l1 = Math.log(XA[1]);
    return Array.from({ length: n + 1 }, (_, i) => {
      const d = Math.exp(l0 + (i / n) * (l1 - l0));
      return [xa(d), ya(success(d, p.h50, beta))] as [number, number];
    });
  };
  if (!onPub) parts.push(el("path", { d: linePath(curvePts(bPub)), fill: "none", stroke: C.ink2, "stroke-width": 1.5, "stroke-dasharray": "4 3" }));
  const main = curvePts(p.beta);
  parts.push(el("path", { d: linePath(main), fill: "none", stroke: C.c1, "stroke-width": 2.5, "stroke-linejoin": "round" }));
  obstacles.push(...lineObstacles(main, 6, 3));

  // Read-offs at 50%, 80%, and q: a guide across the plot at that success
  // level, a dot where it meets the curve, and a drop to the time axis. Each
  // label sits at either end of its guide, above or below it, wherever it
  // clears the curve and the other guides.
  const h50 = p.h50, h80 = horizon(0.8, h50, p.beta), hq = horizon(p.q, h50, p.beta);
  const near = (a: number, b: number) => Math.abs(a - b) < 1e-9;
  const reads: Array<{ q: number; h: number; label: string; strong: boolean }> = [
    { q: 0.5, h: h50, label: tpl(L.at50, { v: dur(h50, lang) }), strong: near(p.q, 0.5) },
    { q: 0.8, h: h80, label: tpl(L.at80, { v: dur(h80, lang) }), strong: near(p.q, 0.8) },
  ];
  if (!near(p.q, 0.5) && !near(p.q, 0.8)) reads.push({ q: p.q, h: hq, label: tpl(L.atQ, { q: pctq(p.q), v: dur(hq, lang) }), strong: true });
  const xEnd = w - rightA;
  const guides: Box[][] = [];
  for (const r of reads) {
    const yy = ya(r.q);
    const inside = r.h >= XA[0];
    const xx = inside ? xa(r.h) : left;
    const col = r.strong ? C.c2 : C.ink2;
    const sw = r.strong ? 1.5 : 1;
    parts.push(el("line", { x1: left, x2: xEnd, y1: yy, y2: yy, stroke: col, "stroke-width": sw, "stroke-dasharray": "4 3" }));
    if (inside) {
      parts.push(el("line", { x1: xx, x2: xx, y1: yy, y2: topA + hA, stroke: col, "stroke-width": sw, "stroke-dasharray": "4 3" }));
      parts.push(el("circle", { cx: xx, cy: yy, r: 4, fill: col, stroke: C.paper, "stroke-width": 1.5 }));
      parts.push(el("path", { d: `M${xx - 4},${topA + hA}L${xx + 4},${topA + hA}L${xx},${topA + hA - 6}Z`, fill: col }));
    } else {
      // Off the axis to the left: an arrow at the edge.
      parts.push(el("path", { d: `M${left + 1},${yy}L${left + 8},${yy - 4}L${left + 8},${yy + 4}Z`, fill: col }));
    }
    guides.push(lineObstacles([[left, yy], [xEnd, yy]], 8, 1));
  }
  const dropped: typeof reads = [];
  {
    const taken: Box[] = [...obstacles];
    const order = reads.map((r, i) => ({ r, i })).sort((a, b) => Number(b.r.strong) - Number(a.r.strong) || b.r.q - a.r.q);
    for (const { r, i } of order) {
      const yy = ya(r.q);
      const others = guides.filter((_, j) => j !== i).flat();
      const cands: Array<[number, number, "start" | "end"]> = [
        [xEnd - 2, yy - 5, "end"], [left + 12, yy - 5, "start"], [xEnd - 2, yy + 5 + fs * 0.78, "end"], [left + 12, yy + 5 + fs * 0.78, "start"],
      ];
      let done = false;
      for (const [tx, ty, anchor] of cands) {
        const box = textBox(tx, ty, r.label, fs, anchor);
        if (box.y0 < topA - 4 || box.y1 > topA + hA - 2 || box.x0 < left + 2 || box.x1 > xEnd) continue;
        if ([...taken, ...others].some((b) => overlaps(b, box))) continue;
        parts.push(text(tx, ty, r.label, { "font-size": fs, "text-anchor": anchor, class: `fig-t-halo fig-t-num${r.strong ? " fig-t-strong" : ""}` }));
        taken.push(box);
        done = true;
        break;
      }
      if (!done) dropped.push(r);
    }
  }

  // The ratio h50 / h80, as a bracket under the time axis.
  y = topA + hA + axisHeight(true, fs) + 10;
  {
    const r = Math.exp(LOGIT80 / p.beta);
    const x80 = Math.max(left, xa(Math.max(h80, XA[0]))), x50 = xa(h50);
    parts.push(el("path", { d: `M${x80},${y - 6}L${x80},${y}L${x50},${y}L${x50},${y - 6}`, fill: "none", stroke: C.ink2, "stroke-width": 1.25 }));
    const lab = tpl(L.ratio, { r: sig(r, 3) });
    const tw = textWidth(lab, fs);
    const cx = Math.min(w - tw / 2, Math.max(tw / 2, (x80 + x50) / 2));
    parts.push(text(cx, y + fs + 5, lab, { "font-size": fs, "text-anchor": "middle", class: "fig-t-num fig-t-strong" }));
    y += fs + 5 + 22;
  }
  // Read-offs that found no room beside their guide are listed here, each
  // with its guide's line style.
  for (const r of dropped) {
    parts.push(el("line", { x1: 0, x2: 16, y1: y - 4, y2: y - 4, stroke: r.strong ? C.c2 : C.ink2, "stroke-width": 1.5, "stroke-dasharray": "4 3" }));
    parts.push(text(22, y, r.label, { "font-size": fs, class: `fig-t-num${r.strong ? " fig-t-strong" : ""}` }));
    y += 18;
  }
  if (dropped.length) y += 8;

  // Readout: the equation's terms.
  {
    const rp: string[] = [];
    const alpha = p.beta * Math.log(h50);
    const rows = [
      tpl(L.eqAlpha, { b: fixed(p.beta, 2), h: sig(h50, 4), a: fixed(alpha, 2) }),
      tpl(L.eqQ, { q: pctq(p.q), l: fixed(logit(p.q), 2), v: dur(hq, lang) }),
      tpl(L.eqRatio, { l8: fixed(LOGIT80, 3), b: fixed(p.beta, 2), r: sig(Math.exp(LOGIT80 / p.beta), 3) }),
    ];
    for (const row of rows) for (const ln of lines(row, lang, fs, w)) { rp.push(text(0, y, ln, { "font-size": fs, class: "fig-t-num" })); y += 17; }
    y += 4;
    const note = onPub ? tpl(L.notePub, { b: fixed(bPub, 2), name: nameOf(m, lang) })
      : tpl(L.noteOff, { name: nameOf(m, lang), b: fixed(bPub, 2), h80: pub(m.p80, lang).v });
    for (const ln of lines(note, lang, fs, w)) { rp.push(text(0, y, ln, { "font-size": fs, class: "fig-t-muted" })); y += 17; }
    parts.push(g({ class: "fig-readout" }, ...rp));
  }

  // ================= panel B: published horizons by release date
  y += 8;
  for (const ln of lines(L.headB, lang, TYPE.label, w)) { y += 18; parts.push(text(0, y, ln, { "font-size": TYPE.label, class: "fig-t-strong" })); }
  y += 12;
  // Legend.
  {
    const items: Array<{ label: string; draw: (x: number, yy: number) => string }> = [
      { label: L.p50, draw: (x, yy) => el("circle", { cx: x + 6, cy: yy - 4, r: 4, fill: C.c1 }) },
      { label: L.p80, draw: (x, yy) => el("path", { d: diamond(x + 6, yy - 4, 5), fill: C.c2 }) },
      { label: L.notFit, draw: (x, yy) => el("circle", { cx: x + 6, cy: yy - 4, r: 3.5, fill: C.paper, stroke: C.ink2, "stroke-width": 1.5 }) },
    ];
    let cx = 0, row = 0;
    for (const it of items) {
      const iw = 18 + textWidth(it.label, fs);
      if (cx > 0 && cx + iw > w) { cx = 0; row++; }
      const yy = y + 14 + row * 20;
      parts.push(it.draw(cx, yy), text(cx + 18, yy, it.label, { "font-size": fs, class: "fig-t-muted" }));
      cx += iw + 16;
    }
    y += 14 + row * 20 + 16;
  }
  const topB = y + 14;
  // The time labels on this axis are wider than percentages, and wider in zh.
  const ticksB = [1 / 60, 1, 60, 600];
  const leftB = Math.max(left, Math.ceil(Math.max(...ticksB.map((v) => textWidth(tickDur(lang)(v), fs)))) + 12);
  const hB = narrow ? 230 : 260;
  const x0 = dayNum("2019-01-01"), x1 = dayNum("2026-07-01");
  const xb = linear([x0, x1], [leftB + 6, w - right - 6]);
  const yb = log(YB, [topB + hB, topB]);
  const years = Array.from({ length: 8 }, (_, i) => dayNum(`${2019 + i}-01-01`));
  parts.push(axis({ scale: xb, orient: "bottom", at: topB + hB, grid: [topB, topB + hB], ticks: years, format: (v) => String(new Date(v * 86400000).getUTCFullYear()), title: L.xB, size: fs }));
  parts.push(axis({ scale: yb, orient: "left", at: leftB, grid: [leftB, w - right], ticks: ticksB, minor: true, format: tickDur(lang), title: L.yB, size: fs }));
  const obsB: Box[] = [];

  // The 16-hour ceiling.
  const yc = yb(CEILING_MIN);
  parts.push(el("line", { x1: leftB, x2: w - right, y1: yc, y2: yc, stroke: C.ink3, "stroke-width": 1.25, "stroke-dasharray": "6 3" }));
  obsB.push(...lineObstacles([[leftB, yc], [w - right, yc]], 8, 1));

  // Trend lines.
  const tr = [trend(p.window, 0), trend(p.window, 1)] as const;
  const emph = [Math.abs(p.q - 0.5) < 1e-9, Math.abs(p.q - 0.8) < 1e-9];
  for (const k of [0, 1] as const) {
    const t = tr[k];
    const ptsT: Array<[number, number]> = [t.x0, t.x1].map((xx) => [xb(xx), yb(2 ** (t.my + t.slope * (xx - t.mx)))]);
    parts.push(el("path", { d: linePath(ptsT), stroke: k ? C.c2 : C.c1, "stroke-width": emph[k] ? 2.5 : 1.75, "stroke-opacity": 0.85, fill: "none" }));
    obsB.push(...lineObstacles(ptsT, 6, 2));
  }

  // Interval bars for the 50% series, then the points.
  for (const mm of MODELS) {
    const cx = xb(dayNum(mm.released));
    const [, lo, hi] = mm.p50;
    parts.push(el("line", { x1: cx, x2: cx, y1: yb(Math.max(YB[0], lo)), y2: yb(Math.min(YB[1], hi)), stroke: C.c1, "stroke-opacity": 0.3, "stroke-width": 1 }));
  }
  const sel = m;
  for (const k of [1, 0] as const) {
    for (const mm of MODELS) {
      const v = (k ? mm.p80 : mm.p50)[0];
      const cx = xb(dayNum(mm.released)), cy = yb(v);
      const inFit = status(mm, p.window) === "fit";
      const col = k ? C.c2 : C.c1;
      const shape = k
        ? el("path", { d: diamond(cx, cy, 5), fill: inFit ? col : C.paper, stroke: col, "stroke-width": 1.5 })
        : el("circle", { cx, cy, r: 4, fill: inFit ? col : C.paper, stroke: col, "stroke-width": 1.5 });
      parts.push(g({ "data-fig-set": `model=${mm.id}`, class: "fig-hit" }, el("circle", { cx, cy, r: 8, fill: "transparent" }), shape));
      obsB.push({ x0: cx - 5, y0: cy - 5, x1: cx + 5, y1: cy + 5 });
    }
  }
  // The chosen model: both intervals, a connector, and a ring.
  {
    const cx = xb(dayNum(sel.released));
    for (const [k, trip] of [[0, sel.p50], [1, sel.p80]] as const) {
      parts.push(el("line", { x1: cx, x2: cx, y1: yb(Math.max(YB[0], trip[1])), y2: yb(Math.min(YB[1], trip[2])), stroke: k ? C.c2 : C.c1, "stroke-width": 2 }));
      for (const v of [trip[1], trip[2]]) if (v > YB[0] && v < YB[1]) parts.push(el("line", { x1: cx - 4, x2: cx + 4, y1: yb(v), y2: yb(v), stroke: k ? C.c2 : C.c1, "stroke-width": 2 }));
    }
    for (const v of [sel.p50[0], sel.p80[0]]) parts.push(el("circle", { cx, cy: yb(v), r: 8, fill: "none", stroke: C.ink, "stroke-width": 1.5 }));
  }
  // Labels: the chosen model, landmarks, and the ceiling.
  {
    const marks = new Set([sel.id, "gpt2", "gpt_4", "claude_mythos_preview_early_inspect"]);
    const reqB: LabelRequest[] = [];
    for (const mm of MODELS) {
      if (!marks.has(mm.id)) continue;
      const isSel = mm.id === sel.id;
      reqB.push({ x: xb(dayNum(mm.released)), y: yb(mm.p50[0]), text: nameOf(mm, lang), size: fs,
        sides: ["above-left", "left", "above", "below-left", "above-right", "right", "below-right"], gap: 10, priority: isSel ? 5 : 2,
        attrs: { class: `fig-t-halo${isSel ? " fig-t-strong" : " fig-t-muted"}` } });
    }
    reqB.push({ x: leftB + 4, y: yc, text: L.ceiling, size: fs, sides: ["above-right", "below-right"], gap: 4, priority: 4, attrs: { class: "fig-t-halo fig-t-muted" } });
    const pl = placeLabels(reqB, { x0: leftB + 2, y0: topB + 2, x1: w - right, y1: topB + hB - 2 }, obsB);
    parts.push(drawLabels(pl.placed));
  }

  // Readout: the chosen model's published values and the trend.
  y = topB + hB + axisHeight(true, fs) + 16;
  {
    const rp: string[] = [];
    const s = status(sel, p.window);
    const head = `${tpl(L.sel, { name: nameOf(sel, lang), date: dateOf(sel.released, lang) })}${lang === "zh" ? "；" : "; "}${s === "fit" ? L.fit : s === "notFrontier" ? L.notFrontier : s === "ceiling" ? L.over : L.window}`;
    for (const ln of lines(head, lang, fs, w)) { rp.push(text(0, y, ln, { "font-size": fs, class: "fig-t-strong" })); y += 17; }
    if (sel.originalSuite) for (const ln of lines(L.original, lang, fs, w)) { rp.push(text(0, y, ln, { "font-size": fs, class: "fig-t-muted" })); y += 17; }
    const r = sel.p50[0] / sel.p80[0];
    const vals = [
      (() => { const a = pub(sel.p50, lang), b = pub(sel.p80, lang); return tpl(L.selVals, { h50: a.v, l50: a.lo, u50: a.hi, h80: b.v, l80: b.lo, u80: b.hi }); })(),
      tpl(L.selBeta, { r: fixed(r, 2), b: fixed(betaOf(sel), 2) }),
    ];
    for (const row of vals) for (const ln of lines(row, lang, fs, w)) { rp.push(text(0, y, ln, { "font-size": fs, class: "fig-t-num" })); y += 17; }
    y += 6;
    const tl = tpl(L.trend, { n: tr[0].n, win: p.window === "all" ? L.winAll : L.win2023, d50: fixed(tr[0].days, 1), d80: fixed(tr[1].days, 1) });
    for (const ln of lines(tl, lang, fs, w)) { rp.push(text(0, y, ln, { "font-size": fs, class: "fig-t-muted" })); y += 17; }
    parts.push(g({ class: "fig-readout" }, ...rp));
  }
  return svg(w, y, describe(st, lang), ...parts);
}

function diamond(cx: number, cy: number, r: number): string {
  return `M${cx},${cy - r}L${cx + r},${cy}L${cx},${cy + r}L${cx - r},${cy}Z`;
}

