// A duration in minutes, in the largest unit that keeps it above 1.
function dur(min: number, lang: Lang, digits = 3): string {
  const u = lang === "zh" ? ["秒", "分钟", "小时", "天"] : ["s", "min", "h", "d"];
  const [v, i] = min < 1 ? [min * 60, 0] : min < 60 ? [min, 1] : min < 2 * 1440 ? [min / 60, 2] : [min / 1440, 3];
  return `${sig(v, digits)} ${u[i]}`;
}
// A published estimate and its interval, as the chapter quotes them: minutes
// to one decimal, or seconds when the estimate is under a minute.
function pub(t: readonly [number, number, number], lang: Lang): { v: string; lo: string; hi: string } {
  const secs = t[0] < 1;
  const num = (m: number) => (secs ? sig(m * 60, 3) : Number(m.toFixed(1)).toLocaleString("en-US", { minimumFractionDigits: 1, maximumFractionDigits: 1 }));
  const unit = secs ? (lang === "zh" ? "秒" : "s") : (lang === "zh" ? "分钟" : "min");
  return { v: `${num(t[0])} ${unit}`, lo: num(t[1]), hi: num(t[2]) };
}
const tickDur = (lang: Lang) => (v: number) => {
  const T: Array<[number, string, string]> = [[0.1 / 60, "0.1 s", "0.1 秒"], [1 / 60, "1 s", "1 秒"], [1 / 6, "10 s", "10 秒"], [1, "1 min", "1 分钟"], [10, "10 min", "10 分钟"], [60, "1 h", "1 小时"], [600, "10 h", "10 小时"], [1440, "1 d", "1 天"], [10080, "1 wk", "1 周"]];
  const hit = T.find((t) => Math.abs(t[0] / v - 1) < 1e-6);
  return hit ? (lang === "zh" ? hit[2] : hit[1]) : dur(v, lang);
};
const pctq = (q: number) => { const v = Math.round(q * 1000) / 10; return `${fixed(v, v % 1 ? 1 : 0)}%`; };

function describe(st: State<P>, lang: Lang): string {
  const L = labels[lang];
  const p = st.p;
  const m = BY_ID.get(p.model) ?? DEFAULT_MODEL;
  const t50 = trend(p.window, 0), t80 = trend(p.window, 1);
  return tpl(L.describe, {
    name: nameOf(m, lang), h50: dur(p.h50, lang), b: fixed(p.beta, 2), h80: dur(horizon(0.8, p.h50, p.beta), lang),
    r: sig(Math.exp(LOGIT80 / p.beta), 3), q: pctq(p.q), hq: dur(horizon(p.q, p.h50, p.beta), lang),
    win: p.window === "all" ? L.winAll : L.win2023, d50: fixed(t50.days, 1), d80: fixed(t80.days, 1),
  });
}

