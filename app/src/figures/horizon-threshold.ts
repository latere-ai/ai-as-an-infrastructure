const LOGIT80 = logit(0.8); // ln 4
const TASKS = 48;
const ATTEMPTS = 8;
const TASK_MIN = 1 / 60, TASK_MAX = 1440; // 1 s to 1 day, in minutes
const XA: [number, number] = [0.1 / 60, 7 * 1440]; // 0.1 s to 1 week
