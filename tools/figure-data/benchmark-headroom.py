# Regenerate app/src/figures/data/benchmark-headroom.ts: every listed entry
# on three leaderboards the capability-horizon chapter cites, for the
# benchmark-headroom figure.
#
# ARC-AGI-2 and ARC-AGI-3 (semi-private sets, ARC Prize-verified): the
# leaderboard's own data files, /media/data/leaderboard/v2.json and v3.json,
# which carry a generatedAt timestamp. Each entry has a score and the model's
# release date as ARC Prize lists it. Kept: entries the leaderboard displays.
# Dropped: the human panel, and the Kaggle competition entries, whose release
# dates in the file are placeholders (the 2025 competition winner is dated
# 3 November 2024). ARC-AGI-3 entries whose id ends in "provider-adapter" were
# run under ARC Prize's provider-adapter harness; the others under its
# standard harness. The best ARC-AGI-2 private-set score, where only
# competition entries run, comes from /media/data/evaluations.json.
#
# Humanity's Last Exam (Scale's leaderboard, no tools): the entries embedded
# in the leaderboard page's React Server Components payload, each with a
# score and the date it was added (createdAt). The page has no documented
# data endpoint, so this parse depends on the page's current markup and
# stops if it finds no entries.
#
# The script also writes three reference values the figure draws, each
# checked by hand against the cited page: the ARC-AGI-2 human panel average
# (60%, ARC Prize's ARC-AGI-2 announcement of 24 March 2025), the ARC-AGI-3
# human result (100%, launch post of 25 March 2026), and a vendor-reported
# HLE score with tools (67.7% for Claude Opus 5.5, Anthropic's launch table).
# The figure draws the last two at the date of the leaderboard read.
#
#   python tools/figure-data/benchmark-headroom.py   (standard library only)

import datetime as dt
import json
import re
import sys
import urllib.request
from pathlib import Path

ARC = "https://arcprize.org/media/data"
HLE = "https://labs.scale.com/leaderboard/humanitys_last_exam"
OUT = Path(__file__).resolve().parents[2] / "app" / "src" / "figures" / "data" / "benchmark-headroom.ts"


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    return urllib.request.urlopen(req).read().decode()


def arc_series(version):
    data = json.loads(fetch(f"{ARC}/leaderboard/{version}.json"))
    rows = []
    for e in data["evaluations"]:
        if not e["display"] or e["modelGroup"] in ("Human", "Kaggle") or not e["modelReleaseDate"]:
            continue
        rows.append({
            "date": e["modelReleaseDate"][:10],
            "score": round(e["score"] * 100, 4),
            "name": e["modelDisplayName"].replace(" ¹", "").strip(),
            "adapter": e["modelId"].endswith("provider-adapter"),
        })
    rows.sort(key=lambda r: (r["date"], -r["score"], r["name"]))
    return data["generatedAt"], rows


def arc2_private_best():
    ev = json.loads(fetch(f"{ARC}/evaluations.json"))
    rows = [e for e in ev if e["datasetId"] == "v2_Private_Eval" and e["modelId"] != "2025_human_panel" and e["display"]]
    best = max(rows, key=lambda e: e["score"])
    return {"score": round(best["score"] * 100, 4), "name": best["modelId"]}


def hle_series():
    html = fetch(HLE)
    chunks = re.findall(r'self\.__next_f\.push\(\[1,"((?:[^"\\]|\\.)*)"\]\)', html, re.S)
    payload = "".join(json.loads('"' + c + '"') for c in chunks)
    m = re.search(r'"entries":\[', payload)
    if not m:
        sys.exit("no entries array in the HLE page; the page markup changed")
    entries, _ = json.JSONDecoder().raw_decode(payload, m.end() - 1)
    rows = [{"date": e["createdAt"][:10], "score": e["score"], "ci": e["confidenceInterval_upper"], "name": e["model"].strip()}
            for e in entries if not e["deprecated"]]
    rows.sort(key=lambda r: (r["date"], -r["score"], r["name"]))
    return rows


def js(v):
    return json.dumps(v, ensure_ascii=False)


def entry_lines(rows, extra=()):
    out = []
    for r in rows:
        fields = [f"date: {js(r['date'])}", f"score: {r['score']}", f"name: {js(r['name'])}"] + [f"{k}: {js(r[k])}" for k in extra]
        out.append("    { " + ", ".join(fields) + " },")
    return out


def main():
    retrieved = dt.date.today().isoformat()
    gen2, arc2 = arc_series("v2")
    gen3, arc3 = arc_series("v3")
    private = arc2_private_best()
    hle = hle_series()
    if not hle:
        sys.exit("no HLE entries parsed")

    lines = [
        "// Leaderboard entries for the benchmark-headroom figure. Generated by",
        "// tools/figure-data/benchmark-headroom.py; do not edit by hand. Scores are",
        "// percent. ARC dates are model release dates as ARC Prize lists them; HLE",
        "// dates are the dates entries were added to Scale's leaderboard.",
        "//",
        f"// ARC Prize: {ARC}/leaderboard/v2.json (generatedAt {gen2}) and v3.json",
        f"// (generatedAt {gen3}); {ARC}/evaluations.json for the private set.",
        f"// Scale: {HLE}.",
        f"// Retrieved {retrieved}.",
        "",
        "export interface Entry { date: string; score: number; name: string }",
        "",
        "export const SOURCE = {",
        f"  retrieved: {js(retrieved)},",
        f"  arcGenerated: {js(gen2[:10])},",
        "} as const;",
        "",
        "// Hand-checked reference values from the cited pages (see the script).",
        "export const REFERENCE = {",
        "  arc2Launch: \"2025-03-24\",",
        "  arc2HumanAverage: 60,",
        "  arc3Launch: \"2026-03-25\",",
        "  arc3Human: 100,",
        "  hleWithTools: { score: 67.7, name: \"Claude Opus 5.5\" },",
        f"  arc2Private: {{ score: {private['score']}, name: {js(private['name'])} }},",
        "} as const;",
        "",
        "export const HLE: readonly (Entry & { ci: number })[] = [",
        *[l.replace("    {", "  {") for l in entry_lines(hle, ("ci",))],
        "];",
        "",
        "export const ARC2: readonly Entry[] = [",
        *[l.replace("    {", "  {") for l in entry_lines(arc2)],
        "];",
        "",
        "// adapter: run under the provider-adapter harness.",
        "export const ARC3: readonly (Entry & { adapter: boolean })[] = [",
        *[l.replace("    {", "  {") for l in entry_lines(arc3, ("adapter",))],
        "];",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} (HLE {len(hle)}, ARC-AGI-2 {len(arc2)}, ARC-AGI-3 {len(arc3)})", file=sys.stderr)


if __name__ == "__main__":
    main()
